/* ------------------------------------------------------------------------
   加盟店窓口の「意図を見る層」と、答えてよい事実の台帳。

   なぜ要る (2026-08-25):
     このシステムは、加盟店から入ってくる文を、全部「ヒアリングへの回答」として
     処理していた。だから、加盟店が こちらに 質問してきたときにも、回答として
     取り込もうとし、答えられずに定型文を返した。

     実際に起きたこと。合同会社アップスの平田様が、フォームを書きながら
       「今シートの記載をしてますが、これは途中で止めたらダメになっちゃいますか？」
     と尋ねてこられた。はっきりした、不安まじりの問いである。
     システムは「どの質問への回答か取り違えている可能性があります」と返した。
     問いに、ひとことも答えていない。

     入ってくる文には、少なくとも三つある。
       ・こちらの設問への 回答
       ・こちらへの 質問
       ・ただの一言(お礼、雑談)
     これらを見分けずに全部「回答」として扱うのが、根の間違いだった。

   この層がすること:
     1) 意図を見分ける(partnerIntent)
     2) 質問には、答えてよい事実(FACT_SHEET)からだけ答える(conciergeFAQ)
        — 台帳に無いことは答えず、担当の大賀に回す。作り話をしない。

   純粋関数だけを置く(env に触れない)。だから機械で端から端まで確かめられる。
   env を要る返信(LLM 経由)は hearing.js 側に置く。
------------------------------------------------------------------------ */

/* 担当の大賀が確認する、という逃げ道。台帳に無いことは、必ずここへ。 */
export const ESCALATE =
  "担当の大賀が確認して、あらためてご連絡します。少々お待ちください。";

/* 答えてよい事実の台帳。ここに書いていないことは、機械に喋らせない。
   料金・制度の具体・契約の約束は、ここには入れない(人が出る)。 */
export const FACT_SHEET = [
  "・ヒアリングの用紙は、途中で止めても大丈夫。区切りのいいところで一度「送信」を押せば、そこまでが保存され、同じリンクからいつでも続きを足せる。前の内容は消えず、足していける。",
  "・ただし、送信するまでは保存されない。長く入力するときは、こまめに送信すると安心。",
  "・分かるところだけで結構。空欄のまま送っても構わない。足りないところは、こちらから改めて伺う。",
  "・既にいただいた内容は、次に用紙を開くと入力済みで出る。同じことを二度書かなくてよい。",
  "・料金・金額・割引の具体は、担当の大賀から案内する(この窓口では答えない)。",
  "・制度・加算・様式の具体、契約・納期・保証の約束は、担当の大賀が確認して連絡する。",
  "・掲載の可否は、適正価格の検証(KIRA)を前提に、運営が確認して進める。",
];

/* 加盟店から届いた1通の意図を見分ける。
   返す: "answer"(回答) | "question"(質問) | "other"(お礼・雑談など)

   見分けの順序に意味がある。
     1) 番号つき(1) 2) / ①②)で始まる → 回答。こちらの複数設問への返事である。
     2) 疑問の形(末尾が ？、または「〜ますか」「大丈夫」等) → 質問。
     3) それ以外 → この関係の既定は回答収集なので、回答として扱う。

   誤分類の害は非対称である。
     ・質問を回答と誤ると: 問いを無視して、答えたことにしてしまう(実害・大)。
     ・回答を質問と誤ると: 取り込まないだけ。生文は残り、人が拾える(実害・小)。
   だから、疑問の兆しがあれば質問側に倒す。 */
export function partnerIntent(text) {
  const t = String(text || "").trim();
  if (!t) return "other";

  // 1) 番号つきの返事は、回答。
  if (/^[\s　]*(?:\(?[1-9１-９]\)?[)）.．、,:：]|[①-⑨])/.test(t)) return "answer";

  // 2) 疑問の形か。末尾の ？ が最も強い兆し。
  const endsQ = /[?？]\s*$/.test(t);
  const interrog = /(ますか|ますでしょうか|ですか[。\s]*$|でしょうか|できますか|大丈夫|平気|ダメ(に|です|でしょう)|止めたら|やめたら|途中で(止|や|中断)|どうすれ|どうしたら|どうやって|どうなる|いつまで|いつから|どこに|どこで|なぜ|どちら|何を(書|記|入力|すれ)|教えて(ください|くれ|ほしい)|わからな|分からな|不安|平問|困っ)/.test(t);
  if (endsQ || interrog) return "question";

  return "answer";
}

/* 決まった問いには、決まった答えを返す(機械で確実に。LLM に頼らない)。
   台帳に無い問いは null を返し、呼ぶ側が LLM か大賀に回す。
   ここで返す文は FACT_SHEET の範囲内でだけ具体を述べる。 */
export function conciergeFAQ(text) {
  const t = String(text || "");

  // 途中で止める / 保存 / 続き
  if (/(途中|とちゅう|一時|下書き|保存|続き|あとで|後で)/.test(t) &&
      /(止|や|やめ|中断|大丈夫|ダメ|平気|消え|なくな|保存|送信|続|できま)/.test(t)) {
    return "途中で止めても大丈夫です。区切りのいいところで一度「送信」を押していただければ、そこまでが保存され、同じリンクからいつでも続きを足せます(前の内容は消えません)。送信するまでは保存されないので、長く入力されるときは、こまめに送信いただけると安心です。";
  }
  // 止めたら/やめたら + ダメ(平田様の実文)。上に掛からない書き方に備える。
  if (/(止めたら|やめたら|中断).*(ダメ|だめ|大丈夫|平気|消え|なくな)/.test(t) ||
      /(ダメ|だめ|大丈夫|平気).*(止め|やめ|中断|途中)/.test(t)) {
    return "途中で止めても大丈夫です。「送信」を押したところまでが保存され、同じリンクから続きを足せます(前の内容は消えません)。送信するまでは保存されないので、こまめに送信いただけると安心です。";
  }
  // 何を書けばいいか / 全部埋める必要があるか / 分からない
  if (/(何を(書|記|入力)|どこまで(書|記|入力)|全部(書|記|入力|埋め)|空欄|埋めな(く|きゃ)|わからな|分からな|書けな|書き方)/.test(t)) {
    return "分かるところだけで結構です。空欄のまま送っていただいても構いません。足りないところは、こちらから改めてお伺いしますので、ご負担のない範囲でお願いします。";
  }
  // 料金(通常は上流で捕まえているが、念のため二重の網)
  if (/(金額|料金|価格|費用|いくら|値段|支払|請求|割引|値引)/.test(t)) {
    return "料金・金額については、担当の大賀からご案内します。少々お待ちください。";
  }
  return null;
}
